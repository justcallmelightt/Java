// MathDemo.java
// 주제: Math 클래스 - static 메소드로 바로 호출하는 수학 함수들
public class MathDemo {
    public static void main(String[] args) {
        // ================================================================
        // 1. Math 클래스의 메소드는 전부 static이다
        // ================================================================
        // static 메소드이기 때문에 객체 생성(new Math()) 없이
        // "클래스이름.메소드이름()" 형태로 바로 호출할 수 있다.
        System.out.println("절댓값: " + Math.abs(-1234));

        System.out.println();

        // ================================================================
        // 2. 반올림 관련 메소드 - ceil, floor, round 차이
        // ================================================================
        // 세 메소드 모두 "소수점 첫째 자리"를 기준으로 처리한다는 점이 헷갈리기 쉽다.
        System.out.println("ceil(12.34)  올림 : " + Math.ceil(12.34));   // 13.0 (무조건 올림)
        System.out.println("floor(45.67) 버림 : " + Math.floor(45.67)); // 45.0 (무조건 버림)
        System.out.println("round(12.3)  반올림: " + Math.round(12.3)); // 12 (5 미만이라 버림)
        System.out.println("round(3.456) 반올림: " + Math.round(3.456)); // 3 (마찬가지)

        // 실수하기 쉬운 부분: ceil()과 floor()는 결과가 double(12.0, 45.0)이지만,
        // round()는 결과가 long/int 형태(12, 3)로 나온다. 반환 타입이 서로 다르다.

        System.out.println();

        // ================================================================
        // 3. 최댓값 / 최솟값
        // ================================================================
        System.out.println("큰 수: " + Math.max(78, 99));
        System.out.println("작은 수: " + Math.min(34, 56));

        System.out.println();

        // ================================================================
        // 4. 거듭제곱 / 제곱근
        // ================================================================
        System.out.println("3의 3제곱: " + Math.pow(3, 3));   // 27.0
        System.out.println("16의 제곱근: " + Math.sqrt(16));   // 4.0

        System.out.println();

        // ================================================================
        // 5. 난수(random) - 0.0 이상 1.0 미만의 실수
        // ================================================================
        double randomValue = Math.random();
        System.out.println("Math.random() 값: " + randomValue);  // 실행할 때마다 다른 값

        // ----------------------------------------------------------------
        // 원하는 범위의 난수를 만들려면 곱하고 더하는 계산이 필요하다.
        // 예: 주사위 눈(1~6) 만들기
        //   Math.random()      -> 0.0 이상 1.0 미만
        //   Math.random() * 6  -> 0.0 이상 6.0 미만
        //   Math.random() * 6 + 1 -> 1.0 이상 7.0 미만
        //   (int) 형변환하면 소수점이 버려지면서 1~6 사이의 정수만 남는다
        int dice = (int) (Math.random() * 6 + 1);
        System.out.println("주사위 눈: " + dice);
    }
}
