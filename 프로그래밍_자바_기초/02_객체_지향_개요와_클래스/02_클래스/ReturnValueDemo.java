// ReturnValueDemo.java
class Calculator {
    // ================================================================
    // 1. void — 결과를 출력만 하고 끝
    // ================================================================
    void printAdd(int a, int b) {
        System.out.println(a + b);
        // 여기서 끝. 결과를 밖으로 꺼내줄 수 없다.
    }

    // ================================================================
    // 2. int — 결과를 밖으로 꺼내줌
    // ================================================================
    int add(int a, int b) {
        return a + b;
    }
    
    // Q) 두 개의 정수 a, b를 받아서 a에서 b를 빼는 printSub, sub 메서드 작성
}

public class ReturnValueDemo {
    public static void main(String[] args) {
        Calculator calc = new Calculator();

        // ================================================================
        // void 메서드 — 출력은 되지만 결과를 저장하거나 쓸 수 없다
        // ================================================================
        calc.printAdd(3, 4); // 7 출력됨

        // int x = calc.printAdd(3, 4); // 컴파일 에러! void는 꺼낼 게 없음

        // ================================================================
        // 반환값 있는 메서드 — 결과를 받아서 원하는 대로 쓸 수 있다
        // ================================================================
        int result = calc.add(3, 4); // 7을 받아서 저장

        System.out.println(result);                    // 저장해서 출력
        System.out.println(calc.add(3, 4));            // 저장 없이 바로 출력
        System.out.println(calc.add(3, 4) * 2);        // 계산에 활용
        System.out.println("합계: " + calc.add(3, 4)); // 문자열에 붙이기
    }
}
