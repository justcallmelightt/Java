public class DebugBasicDemo {
    public static void main(String[] args) {
        int a = 10;
        int b = 3;
        int sum = a + b;
        int diff = a - b;
        int product = a * b;
        int quotient = a / b;

        System.out.println("합: " + sum);
        System.out.println("차: " + diff);
        System.out.println("곱: " + product);
        System.out.println("몫: " + quotient);
    }
}
